import { EXERCISES } from "./exercises";
import { LESSON_TRACKS, LESSONS } from "./lessons";
import { expandProgram, PROGRAM_SEEDS, WEEKS } from "./programs";

/**
 * Renders the content as an idempotent SQL migration. Rows are keyed by slug
 * (never by generated ids), so re-running the seed updates content in place
 * instead of duplicating it.
 */

const q = (value: string): string => `'${value.replaceAll("'", "''")}'`;
const arr = (values: readonly string[]): string =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(", ")}]::text[]`;
const num = (value: number | null): string => (value === null ? "null" : String(value));

export function renderSeedSql(): string {
  const lines: string[] = [
    "-- =============================================================================",
    "-- GENERATED by packages/content (pnpm --filter @goal4me/content generate).",
    "-- Do not edit by hand: change packages/content/src and regenerate.",
    "-- =============================================================================",
    "",
    "-- Exercises (upsert by slug)",
  ];

  for (const e of EXERCISES) {
    lines.push(
      `insert into public.exercises (slug, name, description, form_tips, muscles, difficulty, met, contraindications, is_published)
values (${q(e.slug)}, ${q(e.name)}, ${q(e.description)}, ${arr(e.formTips)}, ${arr(e.muscles)}, ${e.difficulty}, ${e.met}, ${arr(e.contraindications)}, true)
on conflict (slug) do update set name = excluded.name, description = excluded.description,
  form_tips = excluded.form_tips, muscles = excluded.muscles, difficulty = excluded.difficulty,
  met = excluded.met, contraindications = excluded.contraindications, is_published = true;`,
    );
  }

  lines.push("", "-- Easier/harder links (second pass, once every slug exists)");
  for (const e of EXERCISES) {
    if (!e.easier) continue;
    lines.push(
      `update public.exercises set easier_id = (select id from public.exercises where slug = ${q(e.easier)}) where slug = ${q(e.slug)};`,
      `update public.exercises set harder_id = (select id from public.exercises where slug = ${q(e.slug)}) where slug = ${q(e.easier)};`,
    );
  }

  for (const program of PROGRAM_SEEDS) {
    lines.push(
      "",
      `-- Programme: ${program.name}`,
      `insert into public.programs (slug, name, description, goal, level, duration_days, is_premium, is_published)
values (${q(program.slug)}, ${q(program.name)}, ${q(program.description)}, ${q(program.goal)}, ${q(program.level)}, ${WEEKS * 7}, true, true)
on conflict (slug) do update set name = excluded.name, description = excluded.description,
  goal = excluded.goal, level = excluded.level, duration_days = excluded.duration_days, is_published = true;`,
      // Days are rebuilt wholesale; items cascade. Logged sessions keep their history (FK is set null).
      `delete from public.program_days where program_id = (select id from public.programs where slug = ${q(program.slug)});`,
    );
    for (const day of expandProgram(program)) {
      lines.push(
        `insert into public.program_days (program_id, day_number, title, is_rest_day)
values ((select id from public.programs where slug = ${q(program.slug)}), ${day.dayNumber}, ${q(day.title)}, ${day.isRestDay});`,
      );
      if (day.items.length === 0) continue;
      const values = day.items.map(
        (item) =>
          `  (${item.position}, ${q(item.slug)}, ${q(item.phase)}, ${item.rounds}, ${num(item.targetReps)}, ${num(item.targetSeconds)}, ${item.restSeconds})`,
      );
      lines.push(
        `insert into public.program_items (program_day_id, position, exercise_id, phase, rounds, target_reps, target_seconds, rest_seconds)
select d.id, v.position, e.id, v.phase::public.workout_phase, v.rounds, v.reps::smallint, v.seconds::smallint, v.rest
from (values
${values.join(",\n")}
) as v(position, slug, phase, rounds, reps, seconds, rest)
join public.exercises e on e.slug = v.slug
join public.program_days d on d.day_number = ${day.dayNumber}
  and d.program_id = (select id from public.programs where slug = ${q(program.slug)});`,
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

/** Spec (Monetisation): the free tier includes 3 money lessons, one per beginner track. */
export const FREE_LESSON_TRACKS: readonly string[] = ["budgeting", "saving", "debt"];

/** Lessons seed: upsert by slug; the first lesson of each FREE_LESSON_TRACKS track is free. */
export function renderLessonsSql(): string {
  const lines: string[] = [
    "-- =============================================================================",
    "-- GENERATED by packages/content (pnpm --filter @goal4me/content generate).",
    "-- Do not edit by hand: change packages/content/src/lessons.ts and regenerate.",
    "-- =============================================================================",
  ];
  for (const track of LESSON_TRACKS) {
    LESSONS.filter((lesson) => lesson.track === track).forEach((lesson, index) => {
      const position = index + 1;
      const isFree = position === 1 && FREE_LESSON_TRACKS.includes(track);
      lines.push(
        "",
        `insert into public.lessons (slug, track, position, title, body_md, quiz, action, is_premium, is_published)
values (${q(lesson.slug)}, ${q(track)}, ${position}, ${q(lesson.title)}, ${q(lesson.body)},
  ${q(JSON.stringify(lesson.quiz))}::jsonb, ${q(lesson.action)}, ${!isFree}, true)
on conflict (slug) do update set track = excluded.track, position = excluded.position,
  title = excluded.title, body_md = excluded.body_md, quiz = excluded.quiz,
  action = excluded.action, is_premium = excluded.is_premium, is_published = true;`,
      );
    });
  }
  return `${lines.join("\n")}\n`;
}
